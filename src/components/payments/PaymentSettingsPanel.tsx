import { useState } from 'react'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { Save, BellRing, AlarmClock, QrCode, FileText, CalendarDays, Mail } from 'lucide-react'
import { getEmailStatus, getPaymentSettings, sendTestEmail, updatePaymentSettings } from '../../api/staff'
import { useToastStore } from '../../store/toastStore'
import { inr } from '../../lib/payments'

type Form = {
  dueDay: number
  autoGenerateDues: boolean
  reminderDaysBefore: number
  remindOnDueDate: boolean
  overdueReminderIntervalDays: number
  lateFeeEnabled: boolean
  lateFeeType: 'FLAT' | 'PER_DAY'
  lateFeeAmount: string
  lateFeeGraceDays: number
  lateFeeMaxAmount: string
  upiId: string
  upiPayeeName: string
  landlordName: string
  landlordPan: string
  landlordAddress: string
}

const inputCls = 'w-full px-3.5 py-2.5 rounded-xl border border-gray-200 text-sm focus:outline-none focus:ring-2 focus:ring-brand-400 bg-gray-50 focus:bg-white transition-colors'
const labelCls = 'block text-xs font-semibold text-gray-500 mb-1.5'

function Toggle({ checked, onChange, label }: { checked: boolean; onChange: (v: boolean) => void; label: string }) {
  return (
    <button type="button" role="switch" aria-checked={checked} aria-label={label} onClick={() => onChange(!checked)}
      className={`relative w-11 h-6 rounded-full transition-colors shrink-0 ${checked ? 'bg-brand-600' : 'bg-gray-300'}`}>
      <span className={`absolute top-0.5 left-0.5 w-5 h-5 rounded-full bg-white shadow transition-transform ${checked ? 'translate-x-5' : ''}`} />
    </button>
  )
}

function Section({ icon: Icon, title, desc, children, right }: { icon: typeof Save; title: string; desc: string; children?: React.ReactNode; right?: React.ReactNode }) {
  return (
    <div className="bg-white rounded-2xl border border-gray-100 shadow-sm p-6">
      <div className="flex items-start gap-3 mb-4">
        <div className="w-8 h-8 rounded-xl bg-brand-50 flex items-center justify-center shrink-0"><Icon size={15} className="text-brand-600" /></div>
        <div className="flex-1">
          <h3 className="font-bold text-gray-800 text-sm">{title}</h3>
          <p className="text-xs text-gray-400 mt-0.5">{desc}</p>
        </div>
        {right}
      </div>
      {children}
    </div>
  )
}

/** Settings → Payments: due day, reminders, optional late fee (owner's choice), UPI and receipt details. */
export default function PaymentSettingsPanel({ hostelId }: { hostelId: number }) {
  const { data, isLoading } = useQuery({ queryKey: ['payment-settings', hostelId], queryFn: () => getPaymentSettings(hostelId) })
  if (isLoading || !data) {
    return <div className="flex items-center justify-center py-16"><div className="w-8 h-8 rounded-full border-4 border-brand-200 border-t-brand-600 animate-spin" /></div>
  }
  // Keyed by hostel: switching hostels starts a fresh form from that hostel's saved settings
  return <PaymentSettingsForm key={hostelId} hostelId={hostelId} data={data} />
}

/** Shows whether outgoing email works and lets the owner send themselves a test. */
function EmailStatusCard() {
  const { show } = useToastStore()
  const { data } = useQuery({ queryKey: ['email-status'], queryFn: getEmailStatus, retry: false })
  const testMut = useMutation({
    mutationFn: sendTestEmail,
    onSuccess: (r) => r.sent
      ? show('success', 'Test email sent', `Check the inbox (and spam folder) of ${r.to}.`)
      : show('error', 'Test email failed', r.error ?? 'Unknown error'),
    onError: (e: any) => show('error', 'Test email failed', e?.response?.data?.message ?? 'Could not send.'),
  })
  if (!data) return null
  return (
    <Section icon={Mail} title="Email delivery"
      desc={data.enabled ? 'On. Residents get reminders, late-fee notices and PDF receipts by email.' : 'Off. Reminders go by app notification only until the server email settings (.env) are filled in.'}
      right={
        <div className="flex items-center gap-2">
          <span className={`text-[11px] font-semibold px-2 py-0.5 rounded-full ${data.enabled ? 'bg-emerald-50 text-emerald-700' : 'bg-gray-100 text-gray-500'}`}>{data.enabled ? 'Connected' : 'Not set up'}</span>
          {data.enabled && (
            <button type="button" onClick={() => testMut.mutate()} disabled={testMut.isPending}
              className="px-3 py-1.5 rounded-lg text-xs font-semibold border border-gray-200 text-gray-600 hover:bg-gray-50 disabled:opacity-60">
              {testMut.isPending ? 'Sending…' : 'Send test email'}
            </button>
          )}
        </div>
      } />
  )
}

function toForm(data: any): Form {
  return {
      dueDay: data.dueDay ?? 20,
      autoGenerateDues: data.autoGenerateDues ?? true,
      reminderDaysBefore: data.reminderDaysBefore ?? 3,
      remindOnDueDate: data.remindOnDueDate ?? true,
      overdueReminderIntervalDays: data.overdueReminderIntervalDays ?? 3,
      lateFeeEnabled: !!data.lateFeeEnabled,
      lateFeeType: data.lateFeeType ?? 'FLAT',
      lateFeeAmount: data.lateFeeAmount != null && Number(data.lateFeeAmount) > 0 ? String(data.lateFeeAmount) : '',
      lateFeeGraceDays: data.lateFeeGraceDays ?? 5,
      lateFeeMaxAmount: data.lateFeeMaxAmount != null ? String(data.lateFeeMaxAmount) : '',
      upiId: data.upiId ?? '',
      upiPayeeName: data.upiPayeeName ?? '',
      landlordName: data.landlordName ?? '',
      landlordPan: data.landlordPan ?? '',
      landlordAddress: data.landlordAddress ?? '',
  }
}

function PaymentSettingsForm({ hostelId, data }: { hostelId: number; data: any }) {
  const queryClient = useQueryClient()
  const { show } = useToastStore()
  const [f, setF] = useState<Form>(() => toForm(data))

  const saveMut = useMutation({
    mutationFn: (body: Record<string, unknown>) => updatePaymentSettings(hostelId, body),
    onSuccess: (saved) => {
      queryClient.setQueryData(['payment-settings', hostelId], saved)
      show('success', 'Saved', 'Payment settings updated.')
    },
    onError: (e: any) => show('error', 'Not saved', e?.response?.data?.message ?? 'Could not save settings.'),
  })

  const set = <K extends keyof Form>(k: K, v: Form[K]) => setF((s) => ({ ...s, [k]: v }))

  function save(e: React.FormEvent) {
    e.preventDefault()
    if (f.lateFeeEnabled && !(Number(f.lateFeeAmount) > 0)) {
      show('error', 'Late fee amount needed', 'Enter a late fee amount, or turn the late fee off.')
      return
    }
    saveMut.mutate({
      ...f,
      lateFeeAmount: f.lateFeeAmount === '' ? 0 : Number(f.lateFeeAmount),
      lateFeeMaxAmount: f.lateFeeType === 'PER_DAY' && f.lateFeeMaxAmount !== '' ? Number(f.lateFeeMaxAmount) : null,
    })
  }

  const example = (() => {
    const amt = Number(f.lateFeeAmount) || 0
    if (!f.lateFeeEnabled || !amt) return null
    const due = `the ${f.dueDay}${['th', 'st', 'nd', 'rd'][(f.dueDay % 10 > 3 || [11, 12, 13].includes(f.dueDay)) ? 0 : f.dueDay % 10]}`
    if (f.lateFeeType === 'FLAT') return `Rent due on ${due} and still unpaid ${f.lateFeeGraceDays + 1} days later gets a one-time late fee of ${inr(amt)}.`
    const ten = amt * 10
    const capped = f.lateFeeMaxAmount ? Math.min(ten, Number(f.lateFeeMaxAmount)) : ten
    return `Rent due on ${due}: from day ${f.lateFeeGraceDays + 1} after the due date it grows by ${inr(amt)}/day, so it reaches ${inr(capped)} after 10 chargeable days${f.lateFeeMaxAmount ? ` (cap ${inr(f.lateFeeMaxAmount)})` : ''}.`
  })()

  return (
    <form onSubmit={save} className="space-y-4">
      <EmailStatusCard />
      <Section icon={CalendarDays} title="Rent due date" desc="When monthly rent is due. New dues use this day.">
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 items-end">
          <div>
            <label className={labelCls}>Rent due on day</label>
            <select value={f.dueDay} onChange={(e) => set('dueDay', Number(e.target.value))} className={inputCls + ' bg-white'}>
              {Array.from({ length: 28 }, (_, i) => i + 1).map((d) => <option key={d} value={d}>{d} of every month</option>)}
            </select>
          </div>
          <label className="flex items-center gap-3 py-2.5">
            <Toggle checked={f.autoGenerateDues} onChange={(v) => set('autoGenerateDues', v)} label="Auto-create monthly rent" />
            <span className="text-sm text-gray-700">Create each month's rent automatically on the 1st</span>
          </label>
        </div>
      </Section>

      <Section icon={BellRing} title="Reminders" desc="Sent to residents by email and app notification. Set 0 to turn one off.">
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 items-end">
          <div>
            <label className={labelCls}>Days before due date</label>
            <input type="number" min={0} max={15} value={f.reminderDaysBefore} onChange={(e) => set('reminderDaysBefore', Number(e.target.value))} className={inputCls} />
          </div>
          <label className="flex items-center gap-3 py-2.5">
            <Toggle checked={f.remindOnDueDate} onChange={(v) => set('remindOnDueDate', v)} label="Remind on due date" />
            <span className="text-sm text-gray-700">Remind on the due date</span>
          </label>
          <div>
            <label className={labelCls}>When overdue, remind every (days)</label>
            <input type="number" min={0} max={30} value={f.overdueReminderIntervalDays} onChange={(e) => set('overdueReminderIntervalDays', Number(e.target.value))} className={inputCls} />
          </div>
        </div>
      </Section>

      <Section icon={AlarmClock} title="Late fee" desc="Optional. Residents see the policy on their payments page. Only rent that falls due after you turn this on is charged."
        right={<Toggle checked={f.lateFeeEnabled} onChange={(v) => set('lateFeeEnabled', v)} label="Charge a late fee" />}>
        {f.lateFeeEnabled ? (
          <div className="space-y-4">
            <div className="flex gap-1 bg-gray-100 rounded-xl p-1 w-fit">
              {([['FLAT', 'One-time amount'], ['PER_DAY', 'Per day late']] as const).map(([k, l]) => (
                <button key={k} type="button" onClick={() => set('lateFeeType', k)}
                  className={`px-3 py-1.5 rounded-lg text-xs font-medium ${f.lateFeeType === k ? 'bg-white text-gray-900 shadow-sm' : 'text-gray-500'}`}>{l}</button>
              ))}
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
              <div>
                <label className={labelCls}>{f.lateFeeType === 'FLAT' ? 'Late fee (₹)' : 'Late fee per day (₹)'}</label>
                <input type="number" min={1} value={f.lateFeeAmount} onChange={(e) => set('lateFeeAmount', e.target.value)} className={inputCls} />
              </div>
              <div>
                <label className={labelCls}>Grace period (days after due date)</label>
                <input type="number" min={0} max={30} value={f.lateFeeGraceDays} onChange={(e) => set('lateFeeGraceDays', Number(e.target.value))} className={inputCls} />
              </div>
              {f.lateFeeType === 'PER_DAY' && (
                <div>
                  <label className={labelCls}>Maximum late fee (₹, optional)</label>
                  <input type="number" min={0} value={f.lateFeeMaxAmount} onChange={(e) => set('lateFeeMaxAmount', e.target.value)} className={inputCls} />
                </div>
              )}
            </div>
            {example && <p className="text-xs text-gray-500 bg-gray-50 px-3 py-2 rounded-xl">{example} Staff can waive any late fee from Payments.</p>}
          </div>
        ) : (
          <p className="text-sm text-gray-400">Off. Residents are not charged a late fee.</p>
        )}
      </Section>

      <Section icon={QrCode} title="Collect by UPI (no fees)" desc="Residents scan a QR to pay your UPI ID directly, then enter the UTR. You confirm it in Payments → UPI to Verify.">
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
          <div>
            <label className={labelCls}>Your UPI ID</label>
            <input value={f.upiId} onChange={(e) => set('upiId', e.target.value.trim())} placeholder="e.g. blisspg@okhdfcbank" className={inputCls} />
          </div>
          <div>
            <label className={labelCls}>Name shown in the UPI app</label>
            <input value={f.upiPayeeName} onChange={(e) => set('upiPayeeName', e.target.value)} placeholder="e.g. Bliss PG" className={inputCls} />
          </div>
        </div>
      </Section>

      <Section icon={FileText} title="Rent receipt details" desc="Printed on receipts. Residents use these for HRA tax claims; employers usually ask for the landlord's PAN when rent is above ₹1 lakh a year.">
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
          <div>
            <label className={labelCls}>Landlord / owner name</label>
            <input value={f.landlordName} onChange={(e) => set('landlordName', e.target.value)} className={inputCls} />
          </div>
          <div>
            <label className={labelCls}>Landlord PAN</label>
            <input value={f.landlordPan} maxLength={10} onChange={(e) => set('landlordPan', e.target.value.toUpperCase())} placeholder="ABCDE1234F" className={inputCls + ' font-mono'} />
          </div>
          <div className="sm:col-span-2">
            <label className={labelCls}>Landlord address (if different from the hostel)</label>
            <input value={f.landlordAddress} onChange={(e) => set('landlordAddress', e.target.value)} className={inputCls} />
          </div>
        </div>
      </Section>

      <div className="flex items-center gap-3">
        <button type="submit" disabled={saveMut.isPending}
          className="flex items-center gap-2 px-5 py-2.5 rounded-xl text-white text-sm font-semibold shadow-sm hover:opacity-90 transition-opacity disabled:opacity-60"
          style={{ background: 'linear-gradient(135deg, #1d6ea8, #1a8fd1)' }}>
          <Save size={14} /> {saveMut.isPending ? 'Saving…' : 'Save Payment Settings'}
        </button>
      </div>
    </form>
  )
}
